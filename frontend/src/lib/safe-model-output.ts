/**
 * Use only when model text must be inserted into a non-React HTML context.
 * React text nodes already escape these characters and should receive raw text.
 */
export function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

/** Restrict model-generated links to browser-safe HTTP(S) destinations. */
export function safeModelOutputUrl(value: string): string | null {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:" ? url.href : null;
  } catch {
    return null;
  }
}
